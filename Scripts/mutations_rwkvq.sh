#!/bin/bash
# Мутационная проверка деквантизации .rwkvq и типа её выхода.
#
#   ./Scripts/mutations_rwkvq.sh [фильтр тестов]
#
# Деквантизация — это место, где дефект НЕ ПАДАЕТ и НЕ ВЫГЛЯДИТ дефектом.
# Пресет откалиброван под конкретную арифметику; сдвиг в ней даёт веса,
# которые остаются весами — модель считает, текст выходит связный, просто он
# от другой модели. Поэтому эталоны здесь бит-в-бит, а не по допуску, и
# мутации проверяют именно эту границу.
set -uo pipefail
cd "$(dirname "$0")/.."

M=Scripts/mutate.sh
DQ=Sources/RWKVQuant/RwkvqDequant.swift
# (BB больше не мутируется — см. раздел «Проводка типа в бэкбоне»)

FILTER="${1:-RwkvqTests|RwkvqDTypeTests|RwkvqBaseTests|InferenceSmokeTests}"
run() {
    local desc="$1"; shift
    printf '%-52s ' "$desc"
    "$M" "$@" --filter "$FILTER"
}

echo "── Тип выхода ──"

# Тип не доходит до кэша ядер: под оба типа берётся одно и то же
# скомпилированное ядро, и запись float в bf16-буфер даёт мусор.
run "тип выхода не входит в ключ кэша ядер" \
    "$DQ" 'superBlock: gwSb, dtype: outType)' \
          'superBlock: gwSb, dtype: "float")'

# ЗДЕСЬ БЫЛА мутация «буфер выхода размечен как float всегда»
# (`device float* orow = (device float*)out + ...`). Она снята, и причина
# стоит того, чтобы её записать.
#
# MLX объявляет выходной буфер в сигнатуре ядра по outputDTypes, то есть при
# bf16 это `device bfloat16_t* out`. Приведение к `device float*` не
# компилируется — но не при сборке Swift, а при построении metal-библиотеки
# В РАНТАЙМЕ. MLX сообщает об этом Fatal error, после чего процесс xctest
# ОСТАЁТСЯ ВИСЕТЬ на нуле процессорного времени и не возвращает код.
# mutate.sh решает по коду возврата, а его нет вовсе: прогон мутаций
# останавливается насмерть.
#
# То есть мутация не «не поймана» и не «поймана» — она невыразима этим
# инструментом. Проверяемое ею свойство (буфер размечен тем типом, которым
# объявлен) закрыто мутациями «ключ кэша» и «MLX-выход всегда fp32»: обе
# дают то же расхождение разметки и обе завершаются.

# Тип не передаётся в MLX: форма и разметка расходятся.
run "MLX-выход всегда fp32" \
    "$DQ" 'outputDTypes: [dtype])[0]' \
          'outputDTypes: [.float32])[0]'

# Комбайн уезжает в половинную точность — то, от чего предостерегает шапка
# файла и ради чего эталоны сняты бит-в-бит.
run "комбайн считается не во float" \
    "$DQ" 'orow[c] = (\(outType))(float(nib[c]) * sf + mf);' \
          'orow[c] = (\(outType))(half(nib[c]) * half(sf) + half(mf));'

echo
echo "── Проводка типа в бэкбоне ──"
#
# ЗДЕСЬ БЫЛИ мутации «проекция просит fp16 вместо типа вычислений» и
# «таблица эмбеддингов просит fp16». Обе оказались НЕ ПОЙМАНЫ, и разбор
# показал, что дело не в пробеле тестов.
#
# Первое: у fp16 мантисса ДЛИННЕЕ, чем у bf16 (10 бит против 7). Веса RWKV
# лежат внутри единичного диапазона, переполнения нет, и подмена даёт
# результат не хуже, а точнее. Допуском такое не ловится по определению.
#
# Второе, и оно важнее: в бою `x.dtype` почти везде float32 — WKV-шаг
# возвращает fp32 в остаточный поток начиная со слоя 0. Значит любой
# запрошенный тип всё равно повышается матмулом до fp32, и подмена
# НЕ НАБЛЮДАЕМА вообще, ничем. Пока течёт тип активации, эти мутации
# невозможно поймать в принципе; когда течь закроют, их стоит вернуть.
# Свойство «квантованная база не меняет тип прохода» держит
# RwkvqDTypeTests.testQuantizedPassKeepsTheComputeDType.

echo
echo "Итог: смотри строки НЕ ПОЙМАНА выше. Каждая — либо пробел в наборе"
echo "тестов, либо утверждение о том, что мутация безвредна; второе"
echo "нужно обосновать разбором, а не оставлять как есть."
echo
echo "ЗАМЕЧАНИЕ. Мутация «просить fp32 вместо типа вычислений» здесь"
echo "намеренно ОТСУТСТВУЕТ. Она восстанавливает поведение до правки:"
echo "числа те же (matmul всё равно приведёт), меняется только объём"
echo "транзиента и время. Тесты скорость не меряют и поймать её не могут —"
echo "это не пробел в наборе, а граница того, что мутации проверяют вообще."

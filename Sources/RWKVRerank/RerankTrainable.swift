// ───────────────────────────────────────────────────────────────────────
//  ЧТО обучается у реранкера.
//
//  Ответ короткий: только голова. Это не упрощение на первое время, а
//  следствие устройства обучения. Вся экономия здесь стоит на том, что
//  «текст пары → состояние базы» — ФИКСИРОВАННАЯ функция, посчитанная один
//  раз в кэш. Тронь базу LoRA-адаптером — и карта признаков поедет на каждом
//  шаге, кэш станет неверным, а обучение придётся вести с онлайн-кодированием,
//  то есть в сотни раз дороже.
//
//  Поэтому здесь нет ни композиции с базовым множеством, ни режимов: одна
//  реализация, и она честно отражает единственный поддерживаемый сценарий.
// ───────────────────────────────────────────────────────────────────────

/// Обучаемая голова реранкера.
///
/// Подстановка идёт прямо в объект головы (`setParameters`) — вызов
/// происходит ВНУТРИ grad-замыкания, поэтому цепь к fp32-мастеру
/// сохраняется, и forward читает уже трассируемые тензоры.
public final class RerankerHeadTrainableSet: TrainableSet {

    private let head: RerankerHead

    public init(_ head: RerankerHead) {
        self.head = head
    }

    public var parameterNames: [String] { head.parameterNames }

    /// Мастер в fp32. Для головы это не формальность: она инициализируется
    /// весами базы, а официальные чекпоинты лежат в bf16, у которого 8 бит
    /// мантиссы. `RerankerHead` уже приводит веса к fp32 при сборке, здесь
    /// каст остаётся страховкой на случай явного `headDType: .bfloat16`.
    public func initialParameters() -> [MLXArray] {
        let ps = head.parameters.map { $0.asType(.float32) }
        eval(ps)
        return ps
    }

    public func inject(_ ps: [MLXArray]) {
        head.setParameters(ps)
    }

    public func commit(_ ps: [MLXArray]) {
        head.setParameters(ps)
        eval(head.parameters)
    }
}

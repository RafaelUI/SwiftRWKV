import Foundation
import MLX

// ───────────────────────────────────────────────────────────────────────
//  Вычитающая абляция шага обучения — прибор, а не часть счёта.
//
//  Граф MLX ленив, и снять время операции «вокруг вызова» нельзя; а
//  принудительное вычисление внутри трассировки градиента удерживает всё
//  вычисленное до конца трассировки (проверено: шаг 0.4B уходит за 9 ГБ).
//  Поэтому статья меряется вычитанием: её обратный проход подменяется
//  нулями нужной формы, остальной граф не меняется, разность времени шага
//  с подменой и без — цена статьи.
//
//  ГРАДИЕНТЫ ПРИ ВКЛЮЧЁННОЙ ПОДМЕНЕ НЕВЕРНЫ. Только для замеров.
// ───────────────────────────────────────────────────────────────────────
public enum RWKVAblation {
    /// Обратный проход ядра WKV (пересчёт прямого + обратное ядро) → нули.
    public nonisolated(unsafe) static var skipWKVBackward = false
    /// Обратный проход квантованных проекций (деквант + матмул) → нули.
    public nonisolated(unsafe) static var skipProjectionBackward = false
}
